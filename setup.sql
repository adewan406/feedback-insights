-- Snowflake setup for Feedback Insights (read/write service user)
-- Run ONCE in a Snowsight SQL worksheet: select all, then "Run All". Role: ACCOUNTADMIN.

USE ROLE ACCOUNTADMIN;

-- 1. Database + schema
CREATE DATABASE IF NOT EXISTS FEEDBACK_INSIGHTS;
CREATE SCHEMA IF NOT EXISTS FEEDBACK_INSIGHTS.APP;
USE SCHEMA FEEDBACK_INSIGHTS.APP;

-- 2. Tables
-- One row per upload (a CSV or pasted batch).
CREATE TABLE IF NOT EXISTS UPLOADS (
  UPLOAD_ID    STRING PRIMARY KEY,
  UPLOADED_AT  TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  LABEL        STRING,          -- e.g. "Oct 2026"
  FILE_NAME    STRING,
  ITEM_COUNT   NUMBER
);

-- Automation step 1: the raw feedback, exactly as uploaded.
CREATE TABLE IF NOT EXISTS FEEDBACK_RAW (
  UPLOAD_ID    STRING,
  FEEDBACK_ID  STRING,
  FEEDBACK_DATE DATE,
  SOURCE       STRING,
  TEXT         STRING,
  STARS        NUMBER(1, 0),
  LOADED_AT    TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

-- Automation step 2: every agent run and its full report.
CREATE TABLE IF NOT EXISTS AGENT_RUNS (
  RUN_ID       STRING PRIMARY KEY,
  UPLOAD_ID    STRING,
  PREVIOUS_UPLOAD_ID STRING,
  CREATED_AT   TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  STATUS       STRING,          -- running | done | failed
  MODEL        STRING,
  SECONDS      NUMBER,
  REPORT       VARIANT,         -- the whole report as JSON
  ERROR        STRING
);

-- The agent's label for each piece of feedback (lets later runs reuse them).
CREATE TABLE IF NOT EXISTS FEEDBACK_LABELS (
  RUN_ID       STRING,
  UPLOAD_ID    STRING,
  FEEDBACK_ID  STRING,
  THEME        STRING,
  SENTIMENT    STRING
);

-- Automation step 3: notifications shown on the dashboard.
CREATE TABLE IF NOT EXISTS NOTIFICATIONS (
  NOTIFICATION_ID STRING PRIMARY KEY,
  CREATED_AT   TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
  LEVEL        STRING,          -- urgent | info
  TITLE        STRING,
  BODY         STRING,
  RUN_ID       STRING,
  IS_READ      BOOLEAN DEFAULT FALSE,
  EMAILED      BOOLEAN DEFAULT FALSE
);

-- 3. A role that can read and write ONLY these tables (no creating or dropping anything)
CREATE ROLE IF NOT EXISTS FEEDBACK_APP_RW;
GRANT USAGE ON WAREHOUSE SNOWFLAKE_LEARNING_WH TO ROLE FEEDBACK_APP_RW;
GRANT USAGE ON DATABASE FEEDBACK_INSIGHTS TO ROLE FEEDBACK_APP_RW;
GRANT USAGE ON SCHEMA FEEDBACK_INSIGHTS.APP TO ROLE FEEDBACK_APP_RW;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA FEEDBACK_INSIGHTS.APP TO ROLE FEEDBACK_APP_RW;
GRANT SELECT, INSERT, UPDATE, DELETE ON FUTURE TABLES IN SCHEMA FEEDBACK_INSIGHTS.APP TO ROLE FEEDBACK_APP_RW;

